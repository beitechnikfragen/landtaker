"""
Build the Landtaker logo pack and social media kit from the master SVGs.

Everything downstream of brand/images/logo/*.svg is generated by this script —
nothing in dist/ is hand-edited, so a change to a master SVG only needs a rerun.

Run:  python brand/src/make_logo_pack.py
Out:  brand/dist/
"""
import io
import os
import re
import sys

import resvg_py
from PIL import Image, ImageChops, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
BRAND = os.path.dirname(HERE)
SRC = os.path.join(BRAND, "images", "logo")
OUT = os.path.join(BRAND, "dist")

# Palette. The mark uses light for outlines/rims, ink for fills, orange as the
# single accent; slate only appears in a few hairline seams.
LIGHT = "#e8ecef"
INK = "#0d1013"
ORANGE = "#ff8a1f"
SLATE = "#333c45"

# Raster sizes per lockup. Long-form lockups need more pixels to keep the
# wordmark legible, so each variant carries its own list rather than one shared
# set of squares.
SIZES = {
    "mark": [64, 128, 256, 512, 1024],
    "lockup-horizontal": [400, 800, 1600, 2400],
    "lockup-stacked": [300, 600, 1200, 1800],
    "wordmark": [400, 800, 1600, 2400],
}

FAVICON_SIZES = [16, 32, 48, 64, 128, 180, 192, 512]


def render(svg_text, width=None, height=None, background=None):
    """SVG string -> PIL RGBA image."""
    raw = resvg_py.svg_to_bytes(
        svg_string=svg_text,
        width=width,
        height=height,
        background=background,
        shape_rendering="geometric_precision",
    )
    if isinstance(raw, list):
        raw = bytes(raw)
    return Image.open(io.BytesIO(raw)).convert("RGBA")


# --------------------------------------------------------------------------
# Colour variants
#
# The mark is not a flat shape: LIGHT draws the outlines and rims, INK fills the
# body. Recolouring every path to a single value collapses those two roles and
# the mark turns into a blob, so the mono variants below keep the light paths as
# holes instead of painting over them.
# --------------------------------------------------------------------------

def recolor(svg, mapping):
    """Replace fill="#xxx" values according to mapping (case-insensitive)."""
    def sub(m):
        val = m.group(1).lower()
        return 'fill="%s"' % mapping.get(val, m.group(1))

    return re.sub(r'fill="(#[0-9a-fA-F]{6})"', sub, svg)


def variant_color(svg):
    """The master artwork, untouched."""
    return svg


def variant_on_light(svg):
    """
    For light backgrounds: swap the light and ink roles.

    Swapping both ways matters. Recolouring only the light paths to ink — the
    obvious reading of "make it work on white" — turns the shield into a solid
    black slab, because the ink paths that were the fill stay ink and swallow
    the map seams and the rocket. Trading the two roles keeps the plate light
    and the detail dark, so the artwork still reads.

    A hand-authored master takes precedence over this where one exists; see
    ON_LIGHT_MASTERS.
    """
    return recolor(svg, {
        LIGHT.lower(): INK,
        INK.lower(): LIGHT,
        SLATE.lower(): INK,
    })


# Hand-authored light versions, preferred over the generated swap above. The
# horizontal lockup has one because the automatic swap cannot decide which of
# two ink paths is plate and which is detail — a person drew that distinction
# deliberately, and it looks better than anything the recolour produces.
ON_LIGHT_MASTERS = {
    "lockup-horizontal": "lockup-horizontal-light.svg",
}


def variant_mono(svg, color):
    """
    Single-colour silhouette with cut-outs.

    Naively flattening every path to one colour welds the outlines to the fill
    and the mark reads as a blob, so this keeps the two roles apart:

      * the SHAPE is the union of every path — including the light ones, which
        is what keeps the crown (it sits outside the shield and has no ink
        beneath it) and the rocket from disappearing;
      * the light paths are then punched back out, but only where ink lies
        underneath, which is what preserves the map seams as negative space.

    Punching the light paths out unconditionally was the first attempt and it
    deleted the crown outright.
    """
    silhouette = recolor(svg, {
        INK.lower(): color,
        ORANGE.lower(): color,
        SLATE.lower(): color,
        LIGHT.lower(): color,
    })
    holes = recolor(svg, {
        INK.lower(): "none",
        ORANGE.lower(): "none",
        SLATE.lower(): "none",
        LIGHT.lower(): color,
    })
    body = recolor(svg, {
        INK.lower(): color,
        ORANGE.lower(): color,
        SLATE.lower(): color,
        LIGHT.lower(): "none",
    })
    return silhouette, holes, body


def render_mono(svg, color, width):
    """Render a mono variant to RGBA, doing the cut-out in pixel space."""
    silhouette, holes, body = variant_mono(svg, color)

    sil = render(silhouette, width=width)
    hole = render(holes, width=width).split()[3]
    bod = render(body, width=width).split()[3]

    # A light path only becomes a hole where the body actually covers it.
    # Elsewhere (the crown, the rocket tip) it has to stay solid.
    cut = ImageChops.multiply(hole, bod)
    alpha = ImageChops.subtract(sil.split()[3], cut)

    out = Image.new("RGBA", sil.size, color)
    out.putalpha(alpha)
    return out


def mono_svg(svg, color):
    """
    Vector form of the mono variant.

    Same two-layer idea as render_mono, expressed as a mask: the silhouette is
    painted in `color`, then the light paths are removed through a luminance
    mask that is itself clipped to the body. Keeping it as a mask means the
    SVG stays resolution-independent instead of baking in a rasterised cut.
    """
    def inner(s):
        return re.sub(r'^.*?<svg[^>]*>|</svg>\s*$', '', s, flags=re.S)

    head = re.match(r'<svg[^>]*>', svg).group(0)

    # Mirrors render_mono exactly: alpha = silhouette - (holes AND body).
    #
    # The subtraction has to be gated on the body, because a light path with
    # nothing beneath it is structure, not a seam — the crown sits entirely
    # outside the shield and an ungated cut deletes it. Nesting the mask does
    # the gating: `cut` paints the light paths white, but is itself masked by
    # `bodyonly`, so it can only remove pixels the body actually covers.
    white = "#ffffff"
    black = "#000000"

    solid = inner(recolor(svg, {
        INK.lower(): color, ORANGE.lower(): color,
        SLATE.lower(): color, LIGHT.lower(): color,
    }))
    body_white = inner(recolor(svg, {
        INK.lower(): white, ORANGE.lower(): white,
        SLATE.lower(): white, LIGHT.lower(): "none",
    }))
    light_white = inner(recolor(svg, {
        INK.lower(): "none", ORANGE.lower(): "none",
        SLATE.lower(): "none", LIGHT.lower(): white,
    }))

    return (
        '%s<defs>'
        '<mask id="ltbody" maskUnits="userSpaceOnUse">%s</mask>'
        '<mask id="ltmono" maskUnits="userSpaceOnUse">'
        '<rect x="-100%%" y="-100%%" width="300%%" height="300%%" fill="%s"/>'
        '<g fill="%s">%s</g>'
        '<g mask="url(#ltbody)">%s</g>'
        '</mask>'
        '</defs>'
        '<g mask="url(#ltmono)">%s</g></svg>'
        % (
            head,
            body_white,
            black,
            white,
            # Silhouette: every path, so the crown counts as shape.
            inner(recolor(svg, {
                INK.lower(): white, ORANGE.lower(): white,
                SLATE.lower(): white, LIGHT.lower(): white,
            })),
            # Cut: light paths in black, gated to the body by ltbody.
            inner(recolor(svg, {
                INK.lower(): "none", ORANGE.lower(): "none",
                SLATE.lower(): "none", LIGHT.lower(): black,
            })),
            solid,
        )
    )


VARIANTS = {
    "color": variant_color,
    "on-light": variant_on_light,
    "mono-light": lambda s: mono_svg(s, LIGHT),
    "mono-ink": lambda s: mono_svg(s, INK),
}

# Mono PNGs go through render_mono instead of rendering the mask SVG, so the
# cut-out is identical whichever way a consumer picks the file up.
MONO_COLORS = {"mono-light": LIGHT, "mono-ink": INK}


# --------------------------------------------------------------------------
# Wordmark extraction
#
# The wordmark exists only as a <g> inside the horizontal lockup. Pulling it out
# means keeping that group, dropping the mark, and re-fitting the viewBox to what
# is left — the group's own transform tells us where it sits.
# --------------------------------------------------------------------------

def extract_wordmark(lockup_svg):
    m = re.search(
        r'<g fill="([^"]+)" transform="translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)">(.*?)</g>',
        lockup_svg,
        re.S,
    )
    if not m:
        raise SystemExit("wordmark group not found in lockup-horizontal.svg")

    fill, group = m.group(1), m.group(0)

    # Tight bounds come from a probe render rather than from parsing the path
    # data: the glyphs use quadratic segments whose control points sit outside
    # the ink, so arithmetic on the coordinate list clips the outer letters.
    # Rendering once over the parent viewBox and reading the alpha bbox is exact.
    vb = re.search(r'viewBox="([\d.\- ]+)"', lockup_svg).group(1).split()
    px, py, pw, ph = (float(v) for v in vb)

    probe_w = 2000
    probe = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s" width="%d" fill="none">%s</svg>'
        % (" ".join(vb), probe_w, group)
    )
    bbox = render(probe, width=probe_w).split()[3].getbbox()
    if bbox is None:
        raise SystemExit("wordmark probe rendered empty")

    # Probe pixels -> parent user units.
    upp = pw / probe_w
    vb_x = px + bbox[0] * upp
    vb_y = py + bbox[1] * upp
    vb_w = (bbox[2] - bbox[0]) * upp
    vb_h = (bbox[3] - bbox[1]) * upp

    pad = vb_h * 0.08
    vb_x -= pad
    vb_y -= pad
    vb_w += pad * 2
    vb_h += pad * 2

    width = 1200
    height = max(1, round(width * vb_h / vb_w))

    return (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        'viewBox="%.2f %.2f %.2f %.2f" width="%d" height="%d" fill="none">%s</svg>'
        % (vb_x, vb_y, vb_w, vb_h, width, height, group)
    )


def favicon_simplified(svg):
    """
    A reduced cut of the mark for 16px-class favicons.

    Keeps the shield plate and the orange territory and drops everything that
    cannot survive the downscale: the map seams, the rocket, the mushroom cloud
    and the hairline slate seams. The result is the same silhouette and the same
    accent, which is what a favicon actually needs to be identifiable.
    """
    head = re.match(r'<svg[^>]*>', svg).group(0)
    paths = re.findall(r'<path[^>]*/>', svg)

    def bbox(p):
        nums = [float(v) for v in re.findall(r'(-?\d+\.?\d*)', re.search(r'd="([^"]*)"', p).group(1))]
        xs, ys = nums[0::2], nums[1::2]
        return min(xs), min(ys), max(xs), max(ys)

    def area(p):
        x0, y0, x1, y1 = bbox(p)
        return (x1 - x0) * (y1 - y0)

    # The shield plate is simply the largest light path — it spans the whole
    # mark, where every other light path is an interior detail (rocket body,
    # fins, crown). Picking "the first light path" happens to work today but
    # breaks the moment the master is re-exported in a different order.
    light_paths = [p for p in paths if LIGHT in p]
    shield = max(light_paths, key=area)

    # Both orange paths together make the territory; they are contiguous.
    territory = [p for p in paths if ORANGE in p]

    # The plate has to keep its real colouring — dark face, light rim — or the
    # favicon reads as a light badge and stops matching the full logo. The rim
    # is produced by drawing the same outline twice: once in light as the
    # backing, once in ink shrunk about its own centre, leaving the difference
    # visible as an edge.
    x0, y0, x1, y1 = bbox(shield)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    k = 0.955  # rim weight; thick enough to hold up at 16px

    rim = shield
    face = shield.replace(
        'fill="%s"' % LIGHT, 'fill="%s"' % INK
    ).replace(
        'transform="translate(0,0)"',
        'transform="translate(%.2f %.2f) scale(%.4f)"' % (cx * (1 - k), cy * (1 - k), k),
    )

    return head + rim + face + "".join(territory) + "</svg>"


