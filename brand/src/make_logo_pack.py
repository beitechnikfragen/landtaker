# YouTube crops its banner hard on small screens; everything essential has to sit
# inside a 1546x423 box centred on the canvas. The logo is fitted to that box
# rather than to the 2048x1152 canvas, otherwise it renders correctly on desktop
# and gets cropped away on phones.
YT_SAFE = {"youtube-banner": (1546, 423)}

# Horizontal placement, as a fraction of the free space: 0.0 hard left, 0.5
# centred, 1.0 hard right. Reddit puts its own chrome over the left third of a
# community banner, so the logo sits right of it rather than underneath.
ALIGN_X = {
    "reddit-banner": 0.72,
    "reddit-banner-sm": 0.72,
}

# Assets Reddit displays inside a circle. Rendered square, but checked against
# the inscribed circle so nothing important is lost to the clip.
CIRCLE_CROP = {"reddit-icon-256", "reddit-icon-512"}


def compose(logo_img, w, h, fit, bg, accent=None, backdrop=None, safe=None, align_x=0.5):
    """Place the logo on a canvas, fitted into `fit` (fraction of w, of h)."""
    canvas = Image.new("RGBA", (w, h), bg)

    if backdrop is not None:
        canvas.alpha_composite(fit_cover(backdrop, w, h))

    if accent is not None:
        canvas.alpha_composite(accent)

    canvas.alpha_composite(*place(logo_img, w, h, fit, safe, align_x))
    return canvas


def place(logo_img, w, h, fit, safe=None, align_x=0.5):
    """Scale the logo into the fit box and return (image, top-left offset)."""
    # On a platform with a crop-safe area the logo is fitted to that box, so it
    # survives the crop; elsewhere the full canvas is the reference.
    ref_w, ref_h = safe if safe else (w, h)

    fw, fh = fit
    lw, lh = logo_img.size
    scale = min(ref_w * fw / lw, ref_h * fh / lh)
    nw, nh = max(1, round(lw * scale)), max(1, round(lh * scale))

    resized = logo_img.resize((nw, nh), Image.LANCZOS)
    return resized, (round((w - nw) * align_x), (h - nh) // 2)


def check_circle_safe(path, name):
    """
    Assert the artwork in `path` survives a circular clip.

    Compares the mark against the inscribed circle and reports how much ink
    falls outside it. Anything above a hair of antialiasing means the corners
    get shaved off once Reddit applies its own mask.
    """
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    r = min(w, h) / 2.0
    cx, cy = w / 2.0, h / 2.0

    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)

    # Ink = anything visibly different from the flat background, sampled from a
    # corner that the circle never covers.
    bg = im.getpixel((0, 0))
    ink = Image.new("L", (w, h), 0)
    ipx = ink.load()
    src = im.load()
    outside = 0
    total = 0
    mpx = mask.load()
    for y in range(h):
        for x in range(w):
            p = src[x, y]
            if abs(p[0] - bg[0]) + abs(p[1] - bg[1]) + abs(p[2] - bg[2]) > 24:
                total += 1
                ipx[x, y] = 255
                if mpx[x, y] == 0:
                    outside += 1

    if total == 0:
        raise SystemExit("%s: rendered empty" % name)

    pct = outside * 100.0 / total
    if pct > 0.5:
        raise SystemExit(
            "%s: %.1f%% of the mark falls outside the circular crop — "
            "reduce its fit fraction" % (name, pct)
        )
    print("  %s: %.2f%% outside circle (ok)" % (name, pct))


def fit_cover(img, w, h):
    """Scale-and-crop `img` to exactly w x h, preserving aspect."""
    iw, ih = img.size
    scale = max(w / iw, h / ih)
    nw, nh = max(1, round(iw * scale)), max(1, round(ih * scale))
    r = img.resize((nw, nh), Image.LANCZOS)
    return r.crop(((nw - w) // 2, (nh - h) // 2, (nw - w) // 2 + w, (nh - h) // 2 + h))


def accent_bar(w, h):
    """A thin orange rule along the bottom edge — the one brand accent."""
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    bar = max(3, round(h * 0.012))
    layer.paste(Image.new("RGBA", (w, bar), ORANGE), (0, h - bar))
    return layer


def load_backdrop():
    """
    The map render used behind the 'map' social set.

    Dimmed hard: at full strength the terrain competes with the mark, and the
    whole point of a backdrop here is texture, not subject matter.
    """
    path = os.path.join(BRAND, "..", "resources", "images", "EuropeBackground.webp")
    path = os.path.normpath(path)
    if not os.path.exists(path):
        return None

    bd = Image.open(path).convert("RGBA")
    dim = Image.new("RGBA", bd.size, (13, 16, 19, 205))
    bd.alpha_composite(dim)
    return bd


# --------------------------------------------------------------------------

def w(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path


def on_light_svg(lockup, svg):
    """The light-background artwork: hand-authored master if there is one."""
    fname = ON_LIGHT_MASTERS.get(lockup)
    if fname:
        path = os.path.join(SRC, fname)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                return f.read()
    return svg if lockup == "wordmark" else variant_on_light(svg)


def main():
    masters = {}
    for name in ("mark", "lockup-horizontal", "lockup-stacked"):
        with open(os.path.join(SRC, name + ".svg"), encoding="utf-8") as f:
            masters[name] = f.read()

    masters["wordmark"] = extract_wordmark(masters["lockup-horizontal"])

    written = 0

    # ---- SVG + PNG variants -------------------------------------------------
    for lockup, svg in masters.items():
        for vname, fn in VARIANTS.items():
            # A wordmark has no fills to lose, so on-light/mono collapse to a
            # plain recolour of the single glyph group.
            if lockup == "wordmark":
                colors = {"color": LIGHT, "on-light": INK, "mono-light": LIGHT, "mono-ink": INK}
                out_svg = recolor(svg, {LIGHT.lower(): colors[vname]})
            elif vname == "on-light":
                out_svg = on_light_svg(lockup, svg)
            else:
                out_svg = fn(svg)

            svg_path = w(os.path.join(OUT, "svg", lockup, "%s-%s.svg" % (lockup, vname)))
            with open(svg_path, "w", encoding="utf-8") as f:
                f.write(out_svg)
            written += 1

            for size in SIZES[lockup]:
                if vname in MONO_COLORS and lockup != "wordmark":
                    img = render_mono(svg, MONO_COLORS[vname], size)
                else:
                    img = render(out_svg, width=size)
                png_path = w(os.path.join(OUT, "png", lockup, "%s-%s-%dw.png" % (lockup, vname, size)))
                img.save(png_path, "PNG", optimize=True)
                written += 1

    print("logo variants: %d files" % written)

    # ---- Favicons -----------------------------------------------------------
    # Below ~24px the full mark stops resolving: the map seams, the rocket and
    # the mushroom cloud all land inside a couple of pixels and average into
    # mush. The small sizes therefore use a reduced cut — shield plus the orange
    # territory, nothing else — which is still recognisably the same logo at
    # tab size. Anything 32px and up keeps the full artwork.
    fav_svg = masters["mark"]
    fav_small = favicon_simplified(fav_svg)

    fav_imgs = []
    for size in FAVICON_SIZES:
        src = fav_small if size < 32 else fav_svg
        img = render(src, width=size)
        img.save(w(os.path.join(OUT, "favicon", "favicon-%d.png" % size)), "PNG", optimize=True)
        if size in (16, 32, 48):
            fav_imgs.append(img)

    with open(w(os.path.join(OUT, "favicon", "favicon-small.svg")), "w", encoding="utf-8") as f:
        f.write(fav_small)

    # Apple touch icons must be opaque — iOS composites them onto white
    # otherwise, and the dark mark on white loses its outlines.
    apple = render(fav_svg, width=180, background=INK)
    apple.save(w(os.path.join(OUT, "favicon", "apple-touch-icon.png")), "PNG", optimize=True)

    fav_imgs[0].save(
        w(os.path.join(OUT, "favicon", "favicon.ico")),
        format="ICO",
        sizes=[(16, 16), (32, 32), (48, 48)],
    )
    print("favicons: %d files" % (len(FAVICON_SIZES) + 2))

    # ---- Social kit ---------------------------------------------------------
    backdrop = load_backdrop()
    if backdrop is None:
        print("warning: EuropeBackground.webp missing — skipping the map set")

    # Render each lockup once at high resolution and downscale per target;
    # re-rendering the SVG per social asset would be slower for no gain.
    hi = {k: render(v, width=3000) for k, v in masters.items()}

    # The on-light recolour, rendered once per lockup rather than per target.
    hi_light = {
        k: render(on_light_svg(k, v), width=3000)
        for k, v in masters.items()
    }

    social_count = 0
    for name, sw, sh, lockup, fit, note in SOCIAL:
        safe = YT_SAFE.get(name)
        ax = ALIGN_X.get(name, 0.5)

        # A circular-crop asset gets no accent rule: the bar runs along the
        # bottom edge of the square and the clip removes all but its middle,
        # which reads as a stray orange smudge rather than a deliberate rule.
        bar = None if name in CIRCLE_CROP else accent_bar(sw, sh)

        # Plain set: mark on brand ink, orange rule at the foot.
        plain = compose(hi[lockup], sw, sh, fit, INK, accent=bar, safe=safe, align_x=ax)
        plain.save(w(os.path.join(OUT, "social", "plain", name + ".png")), "PNG", optimize=True)
        social_count += 1

        # Light set: the on-light variant so the mark reads against #e8ecef.
        light = compose(hi_light[lockup], sw, sh, fit, LIGHT, accent=bar, safe=safe, align_x=ax)
        light.save(w(os.path.join(OUT, "social", "light", name + ".png")), "PNG", optimize=True)
        social_count += 1

        if backdrop is not None:
            mapped = compose(
                hi[lockup], sw, sh, fit, INK,
                accent=bar, backdrop=backdrop, safe=safe, align_x=ax,
            )
            mapped.save(w(os.path.join(OUT, "social", "map", name + ".png")), "PNG", optimize=True)
            social_count += 1

            # The og card is also the link preview the game server serves, and
            # only brand/images/ is published as an asset root — dist/ is not.
            # Writing it here keeps the served copy from going stale when a
            # master SVG changes.
            if name == "og-1200x630":
                mapped.save(
                    w(os.path.join(BRAND, "images", "social", name + ".png")),
                    "PNG", optimize=True,
                )
                social_count += 1

        # Transparent: same geometry, no canvas — for dropping onto anything.
        canvas = Image.new("RGBA", (sw, sh), (0, 0, 0, 0))
        canvas.alpha_composite(*place(hi[lockup], sw, sh, fit, safe, ax))
        canvas.save(w(os.path.join(OUT, "social", "transparent", name + ".png")), "PNG", optimize=True)
        social_count += 1

    print("social: %d files" % social_count)

    # Reddit clips its icons to a circle. Verify the artwork actually survives
    # that clip rather than trusting the fit fraction — a mark that overflows
    # the inscribed circle loses its corners in the live UI, where it is too
    # late to notice.
    for name in sorted(CIRCLE_CROP):
        check_circle_safe(os.path.join(OUT, "social", "plain", name + ".png"), name)

    print("done -> %s" % OUT)


if __name__ == "__main__":
    main()
